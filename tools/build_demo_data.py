"""Build the public demo dataset the hosted app runs on (Streamlit Community Cloud has no `outputs/`).

    uv run python tools/build_demo_data.py [--region ma_ngrid_blackstone]

Copies one screened region from outputs/<region>/ into demo_data/<region>/ with private owners masked:
- metrics.pkl / lots.pkl: individual and trust owners replaced by "Private owner N" (outputs.redact_private_owners),
  owner_key recomputed from the masked values.
- inputs.gpkg: the layers the app and site cards draw (polygons simplified to 1 m), but the raw parcels layer keeps only id + geometry
  (no owner names or mailing addresses), and feeders keep only the columns the map uses.
"""
from __future__ import annotations

import argparse
import json
import pickle
import shutil
import sys
from pathlib import Path

import pyogrio
import geopandas as gpd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from reservoir import outputs  # noqa: E402
from reservoir.config import load_region  # noqa: E402

DEMO = ROOT / "demo_data"
KEEP = {"feeders": ["feeder_id", "hc_mw", "substation", "voltage_kv"]}
DROP = {"buildings", "roads"}  # used by the analysis step only; the app and cards never draw them
SIMPLIFY = {"wetlands", "flood", "open_space", "parcels"}  # 1 m tolerance: invisible at card/map scale


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--region", default="ma_ngrid_blackstone")
    a = ap.parse_args()
    region = load_region(a.region)
    src = ROOT / "outputs" / a.region
    dst = DEMO / a.region
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)

    metrics = pickle.loads((src / "metrics.pkl").read_bytes())
    lots = pickle.loads((src / "lots.pkl").read_bytes())
    metrics, lots = outputs.redact_private_owners(region, metrics, lots)
    pf = region.parcel_fields
    for f in (metrics, lots):
        if "owner_key" in f:
            f["owner_key"] = [outputs.owner_key(n, ad) for n, ad in zip(f[pf["owner_name"]], f[pf["owner_address"]])]
    (dst / "metrics.pkl").write_bytes(pickle.dumps(metrics))
    (dst / "lots.pkl").write_bytes(pickle.dumps(lots))

    pid = pf["parcel_id"]
    for name, _ in pyogrio.list_layers(src / "inputs.gpkg"):
        if name in DROP:
            continue
        g = gpd.read_file(src / "inputs.gpkg", layer=name)
        if name in SIMPLIFY:
            g["geometry"] = g.geometry.simplify(1.0, preserve_topology=True)
        if name == "parcels":
            g = g[[pid, "_town", "geometry"]]
        elif name in KEEP:
            g = g[[c for c in KEEP[name] if c in g] + ["geometry"]]
        g.to_file(dst / "inputs.gpkg", layer=name, driver="GPKG")

    meta = json.loads((src / "run_meta.json").read_text())
    meta["demo"] = "Private individual and trust owners masked; generated by tools/build_demo_data.py"
    (dst / "run_meta.json").write_text(json.dumps(meta, indent=2))
    for p in sorted(dst.iterdir()):
        print(f"{p.relative_to(ROOT)}  {p.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
